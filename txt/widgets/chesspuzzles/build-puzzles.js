/* Builds chesspuzzles-data.js — original mate-in-1/2/3 puzzles mined from the
 * Cade chess engine playing itself (a strong side against a loose one, from
 * randomised openings). Every puzzle is proven with the exact mate solver: a
 * forced mate in exactly n, and only one first move does it. Not loaded by the
 * app. Run: node txt/widgets/chesspuzzles/build-puzzles.js [seed]
 * (takes a few minutes; prints progress). */
'use strict';
var fs = require('fs'), path = require('path');
var E = require('../chess/chess-engine.js');

var WANT = { 1: 62, 2: 62, 3: 48 };
var seed = +(process.argv[2] || 20261031) >>> 0;
var rand = E.rng(seed);
var got = { 1: [], 2: [], 3: [] }, seen = new Set();

function full() { return got[1].length >= WANT[1] && got[2].length >= WANT[2] && got[3].length >= WANT[3]; }
function boardKey(fen) { return fen.split(' ').slice(0, 2).join(' '); }

function rating(pos, n, first) {
  var r = { 1: 650, 2: 1100, 3: 1500 }[n];
  var from = E.mFrom(first), to = E.mTo(first), fl = E.mFlags(first), pc = pos.b[from] & 7, cap = pos.b[to] & 7;
  var VAL = [0, 1, 3, 3, 5, 9, 0];
  pos.make(first);
  var check = pos.inCheck(), replies = pos.legalMoves().length, attacked = pos.attacked(to, pos.side), defended = pos.attacked(to, pos.side ^ 1);
  pos.unmake();
  if (!check) r += 160;
  if (!(fl & E.F_CAP)) r += 80;
  if (attacked && VAL[pc] > VAL[cap] + (defended ? 1 : -9)) r += 140;      // a sacrifice
  if (pc === 1 && E.mPromo(first) && E.mPromo(first) !== 5) r += 120;       // under-promotion
  r += Math.min(120, replies * 6);
  var checks = 0, ms = pos.legalMoves();
  ms.forEach(function (m) { pos.make(m); if (pos.inCheck()) checks++; pos.unmake(); });
  r += Math.min(100, checks * 12);
  return Math.max(400, Math.min(2400, Math.round(r / 10) * 10));
}

function matDiff(pos) { var m = E.material(pos); return pos.side ? -m.diff : m.diff; }

function consider(pos, ply, game) {
  var fen = pos.fen(), key = boardKey(fen);
  if (seen.has(key)) return false;
  var probe = E.search(pos, { nodes: 30000 });
  if (!probe || probe.mate <= 0 || probe.mate > 3) {
    if (!E.mateAttack(pos, 1)) return false;
  }
  var memo = new Map(), n = E.mateDistance(pos, 3, memo);
  if (!n || got[n].length >= WANT[n]) return false;
  if (matDiff(pos) > 12) return false;                       // no "you're a queen and two rooks up" puzzles
  var ms = E.mateMoves(pos, n, memo);
  if (ms.length !== 1) return false;
  if (n === 1) {                                               // mate in one: make them look for it
    var checks = 0;
    pos.legalMoves().forEach(function (m) { pos.make(m); if (pos.inCheck()) checks++; pos.unmake(); });
    if (checks < 2) return false;
  }
  var line = E.solutionLine(fen, n);
  var v = E.verifyPuzzle(fen, n);
  if (!v.ok || v.uci !== line[0]) return false;
  seen.add(key);
  got[n].push({ fen: fen, n: n, rating: rating(pos, n, ms[0]), line: line, game: game, ply: ply });
  return true;
}

function playGame(g) {
  var pos = E.fromFEN(E.START_FEN), strong = rand() < 0.5 ? 0 : 1, lastHit = -99;
  var weakLv = rand() < 0.5 ? 1 : 2, strongNodes = 12000 + Math.floor(rand() * 30000), hits = 0;
  var openN = 2 + Math.floor(rand() * 6);
  for (var ply = 0; ply < 160; ply++) {
    var st = E.status(pos);
    if (st.over) break;
    if (ply >= 12 && ply - lastHit > 6 && hits < 3 && consider(pos, ply, g)) { lastHit = ply; hits++; }
    var mv;
    if (ply < openN) { var lm = pos.legalMoves(); mv = lm[Math.floor(rand() * lm.length)]; }
    else if (pos.side === strong) mv = E.search(pos, { nodes: strongNodes, rand: rand }).move;
    else { var o = E.levelOpts(weakLv); o.rand = rand; mv = E.search(pos, o).move; }
    pos.make(mv);
  }
}

var t0 = Date.now();
for (var g = 0; !full() && g < 4000; g++) {
  playGame(g);
  if (g % 10 === 9) console.log('game ' + (g + 1) + ': m1 ' + got[1].length + ' m2 ' + got[2].length + ' m3 ' + got[3].length + ' (' + ((Date.now() - t0) / 1000).toFixed(0) + ' s)');
}
var all = got[1].concat(got[2], got[3]);
// shuffle (seeded) so the daily puzzle mixes lengths
for (var i = all.length - 1; i > 0; i--) { var j = Math.floor(rand() * (i + 1)), t = all[i]; all[i] = all[j]; all[j] = t; }
var lines = all.map(function (p) { return JSON.stringify(p.fen + '|' + p.n + '|' + p.rating + '|' + p.line.join(' ')); });
var out = '/* Generated by build-puzzles.js — do not edit by hand.\n' +
  '   Original puzzles mined from the Cade chess engine playing itself; each one is\n' +
  '   proven by the exact mate solver (forced mate in exactly n, unique first move).\n' +
  '   One puzzle per string: FEN | n (mate in n) | rating | main line (UCI).\n' +
  '   Daily puzzle = (days since epoch) mod count. Public domain (CC0). */\n' +
  'window.__cadeChessPuzzles = {"v":1,"epoch":"2026-11-01","p":[\n' + lines.join(',\n') + '\n]};\n';
fs.writeFileSync(path.join(__dirname, 'chesspuzzles-data.js'), out);
console.log('wrote ' + all.length + ' puzzles in ' + ((Date.now() - t0) / 1000).toFixed(0) + ' s');
