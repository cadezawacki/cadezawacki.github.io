#!/usr/bin/env node
/* Builds lettertiles-words.js (the Letter Tiles dictionary).  Usage:
 *   node build-words.js [cache-dir]
 * Downloads its pinned, openly licensed source into cache-dir on first run
 * (Node's fetch, falling back to curl, which honours HTTPS_PROXY) and writes
 * lettertiles-words.js next to this script.
 *
 * Source: word-list@4.1.0 (MIT, Sindre Sorhus; the Letterpress / atebits word
 * list with common bad words removed). Kept: words of 2..15 letters a-z, minus
 * a short drop list of offensive / crude words.
 *
 * Encoding: one string per initial letter, front-coded: every word is written
 * as a digit (how many leading letters it shares with the word before it,
 * capped at 9) followed by the rest of the word. Sorted, so the game can build
 * its trie in one pass. */
'use strict';
var fs = require('fs');
var path = require('path');
var os = require('os');
var cp = require('child_process');

var HERE = __dirname;
var CACHE = process.argv[2] || path.join(os.tmpdir(), 'cade-lettertiles-cache');
var WORDLIST = 'https://cdn.jsdelivr.net/npm/word-list@4.1.0/words.txt';

// ROT13 so the source stays readable for everyone: offensive / crude words.
var DROP_ROT13 = 'nff phz sht tnl wrj gvg frk cbea cbeab nany nahf obbo obbof ohgg ohggf penc pbpx pbpxf phag phagf phzf ' +
  'qvpx qvpxf qlxr qlxrf snt sntf shpx shpxf shpxre shpxref shpxrq shpxvat ubzb ubzbf wvfz wvmm xvxr xvxrf cvff cvffrq cvffvat ' +
  'fuvg fuvgf fuvggl fuvggrq fyhg fyhgf fcvp fcvpf gvgf gjng gjngf jnax jnaxf jnaxre jnaxref juber jubere juberf anmv anmvf ' +
  'ovgpu ovgpurf ovgpul qvyqb qvyqbf ubeal cravf cravfrf chffl chffvrf fcrez fzrtzn frzra dhrre dhrref ovzob ovzobf fchax ' +
  'arteb arterf arteb tbbx tbbxf pbba pbbaf fcnm puvax puvaxf jbc jbcf ubbxre fyhggl grng grngf ernaz ohgguraq ohggubyr ' +
  'nffubyr nffubyrf ovgpurq ovgpuvat pbpxfhpxre zbgureshpxre qbhpur qbhpurf xabo';

function rot13(s) { return s.replace(/[a-z]/g, function (c) { return String.fromCharCode((c.charCodeAt(0) - 84) % 26 + 97); }); }

async function get(url) {
  var file = path.join(CACHE, url.replace(/[^a-z0-9.]+/gi, '_'));
  if (fs.existsSync(file)) return fs.readFileSync(file, 'utf8');
  var text;
  try {
    var res = await fetch(url);
    if (!res.ok) throw new Error(url + ' -> HTTP ' + res.status);
    text = await res.text();
  } catch (e) {
    text = cp.execFileSync('curl', ['-sSfL', url], { encoding: 'utf8', maxBuffer: 1 << 28 });
  }
  fs.mkdirSync(CACHE, { recursive: true });
  fs.writeFileSync(file, text);
  return text;
}

async function main() {
  var drop = new Set(rot13(DROP_ROT13).split(/\s+/).filter(Boolean));
  var words = Array.from(new Set((await get(WORDLIST)).split('\n').map(function (w) { return w.trim(); })
    .filter(function (w) { return /^[a-z]{2,15}$/.test(w) && !drop.has(w); }))).sort();
  var parts = [];
  for (var c = 0; c < 26; c++) {
    var ch = String.fromCharCode(97 + c), prev = '', out = '';
    words.forEach(function (w) {
      if (w.charAt(0) !== ch) return;
      var k = 0;
      while (k < 9 && k < prev.length && k < w.length && prev.charAt(k) === w.charAt(k)) k++;
      out += k + w.slice(k);
      prev = w;
    });
    parts.push(out);
  }
  var js = '/* Generated by build-words.js — do not edit by hand.\n' +
    '   The Letter Tiles dictionary: ' + words.length + ' words of 2-15 letters, one front-coded\n' +
    '   string per initial letter (a digit = letters shared with the previous word, then the rest).\n' +
    '   Source: word-list@4.1.0 — MIT License, Copyright (c) Sindre Sorhus <sindresorhus@gmail.com>\n' +
    '   (https://sindresorhus.com); derived from the atebits/Words list. A few offensive words dropped.\n\n' +
    '   Permission is hereby granted, free of charge, to any person obtaining a copy of this software and\n' +
    '   associated documentation files (the "Software"), to deal in the Software without restriction,\n' +
    '   including without limitation the rights to use, copy, modify, merge, publish, distribute,\n' +
    '   sublicense, and/or sell copies of the Software, and to permit persons to whom the Software is\n' +
    '   furnished to do so, subject to the following conditions: The above copyright notice and this\n' +
    '   permission notice shall be included in all copies or substantial portions of the Software.\n' +
    '   THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND. */\n' +
    '(function (D) {\n' +
    '  if (typeof window !== \'undefined\') window.__cadeLetterTilesWords = D;\n' +
    '  if (typeof module !== \'undefined\' && module.exports) module.exports = D;\n' +
    '})({ n: ' + words.length + ', p: [\n' + parts.map(function (p) { return '"' + p + '"'; }).join(',\n') + '\n]});\n';
  fs.writeFileSync(path.join(HERE, 'lettertiles-words.js'), js);
  console.log('words', words.length, 'bytes', js.length);
}

main().catch(function (e) { console.error(e); process.exit(1); });
